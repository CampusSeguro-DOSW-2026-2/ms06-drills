package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.entity.enums.ExternalModule;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;

/**
 * A call to CHI, BEI or ALE that failed when an event started. The event starts anyway, so
 * the failure is kept here and repeated later until the other service answers.
 * There is one row per event and module.
 */
@Entity
@Table(name = "event_start_failures")
public class EventStartFailureEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event that started. */
    @Column(name = "event_id", nullable = false, updatable = false)
    private UUID eventId;

    /** Service that did not answer. */
    @Enumerated(EnumType.STRING)
    @Column(name = "module", nullable = false, updatable = false, length = 10)
    private ExternalModule module;

    /** Reason of the last failure. */
    @Column(name = "last_error", length = 500)
    private String lastError;

    /** Number of calls that failed. */
    @Column(name = "attempts", nullable = false)
    private int attempts;

    /** Time when the call finally worked; empty while it is pending. */
    @Column(name = "resolved_at")
    private Instant resolvedAt;

    /** Tells if the call is still pending. */
    public boolean isOpen() {
        return resolvedAt == null;
    }

    public UUID getId() {
        return id;
    }

    public UUID getEventId() {
        return eventId;
    }

    public void setEventId(UUID eventId) {
        this.eventId = eventId;
    }

    public ExternalModule getModule() {
        return module;
    }

    public void setModule(ExternalModule module) {
        this.module = module;
    }

    public String getLastError() {
        return lastError;
    }

    public void setLastError(String lastError) {
        this.lastError = lastError;
    }

    public int getAttempts() {
        return attempts;
    }

    public void setAttempts(int attempts) {
        this.attempts = attempts;
    }

    public Instant getResolvedAt() {
        return resolvedAt;
    }

    public void setResolvedAt(Instant resolvedAt) {
        this.resolvedAt = resolvedAt;
    }
}
