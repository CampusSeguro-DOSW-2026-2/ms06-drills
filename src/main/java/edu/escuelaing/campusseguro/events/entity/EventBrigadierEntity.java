package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.entity.enums.BrigadierStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;

/**
 * Local copy of a brigadier assigned to an event. The source of truth is BEI
 * (MS05), where the brigadier self-assigns; MS06 syncs it periodically and keeps
 * the last data, with its timestamp, if BEI stops responding.
 */
@Entity
@Table(name = "event_brigadiers")
public class EventBrigadierEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event it belongs to. */
    @Column(name = "event_id", nullable = false, updatable = false)
    private UUID eventId;

    /** Brigadier identifier in BEI. */
    @Column(name = "brigadier_id", nullable = false, length = 64)
    private String brigadierId;

    /** Brigadier name. */
    @Column(name = "name", length = 150)
    private String name;

    /** Zone chosen in the self-assignment. */
    @Column(name = "zone_id", length = 64)
    private String zoneId;

    /** Active or inactive. */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private BrigadierStatus status;

    /** Last time this data was synced with BEI. */
    @Column(name = "synced_at", nullable = false)
    private Instant syncedAt;

    public UUID getId() { return id; }

    public UUID getEventId() { return eventId;}
    public void setEventId(UUID eventId) { this.eventId = eventId; }

    public String getBrigadierId() { return brigadierId; }
    public void setBrigadierId(String brigadierId) { this.brigadierId = brigadierId; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getZoneId() { return zoneId; }
    public void setZoneId(String zoneId) { this.zoneId = zoneId; }

    public BrigadierStatus getStatus() { return status; }
    public void setStatus(BrigadierStatus status) { this.status = status; }

    public Instant getSyncedAt() { return syncedAt; }
    public void setSyncedAt(Instant syncedAt) { this.syncedAt = syncedAt; }
}
