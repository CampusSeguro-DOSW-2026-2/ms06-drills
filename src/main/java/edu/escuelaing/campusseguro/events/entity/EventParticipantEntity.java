package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.security.Role;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.util.UUID;

/**
 * User type (role) invited to an event. General alerts reach the users who
 * have any of the invited roles.
 */
@Entity
@Table(name = "event_participants")
public class EventParticipantEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event it belongs to. */
    @Column(name = "event_id", nullable = false, updatable = false)
    private UUID eventId;

    /** Invited role. */
    @Enumerated(EnumType.STRING)
    @Column(name = "role", nullable = false, length = 20)
    private Role role;

    public UUID getId() { return id; }

    public UUID getEventId() { return eventId; }
    public void setEventId(UUID eventId) { this.eventId = eventId; }

    public Role getRole() { return role; }
    public void setRole(Role role) { this.role = role; }
}
