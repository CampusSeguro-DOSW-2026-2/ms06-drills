package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.entity.enums.EventStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.JoinTable;
import jakarta.persistence.ManyToMany;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;

/**
 * Emergency event or drill.
 *
 * It is a drill if one of its types has the code {@code SIMULACRO}. The
 * {@code simulacro} field stores that result so it can be filtered easily; the
 * service keeps it up to date. {@code endedAt} is the real time when "Finish"
 * was pressed: there is no scheduled end date.
 *
 * It uses optimistic locking ({@code version}); the service can also ask for
 * a pessimistic lock so two actions cannot change the state at the same time.
 */
@Entity
@Table(name = "events")
public class EventEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event name. */
    @Column(name = "name", nullable = false, length = 150)
    private String name;

    /** Goal and context; can be empty. */
    @Column(name = "description", length = 1000)
    private String description;

    /** Current status. */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    private EventStatus status;

    /** True if it is a drill (it has the Simulacro type). */
    @Column(name = "simulacro", nullable = false)
    private boolean simulacro;

    /** Scheduled start date and time; empty in Draft. */
    @Column(name = "scheduled_start")
    private Instant scheduledStart;

    /** Real time when it changed to In progress. */
    @Column(name = "started_at")
    private Instant startedAt;

    /** Real time when Finish was pressed. */
    @Column(name = "ended_at")
    private Instant endedAt;

    /** User who created the event. */
    @Column(name = "created_by", nullable = false, length = 64)
    private String createdBy;

    /** Version for optimistic locking. */
    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    /** Event types: just 4 per event. */
    @ManyToMany
    @JoinTable(
            name = "event_type_links",
            joinColumns = @JoinColumn(name = "event_id"),
            inverseJoinColumns = @JoinColumn(name = "type_id"))
    private Set<EventTypeEntity> types = new HashSet<>();

    public Set<EventTypeEntity> getTypes() { return types; }
    public void setTypes(Set<EventTypeEntity> types) { this.types = types; }

    public UUID getId() { return id; }

    public String getName() {return name; }
    public void setName(String name) { this.name = name;}
    
    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public EventStatus getStatus() { return status; }
    public void setStatus(EventStatus status) { this.status = status; }

    public boolean isSimulacro() { return simulacro; }
    public void setSimulacro(boolean simulacro) { this.simulacro = simulacro; }

    public Instant getScheduledStart() { return scheduledStart; }
    public void setScheduledStart(Instant scheduledStart) { this.scheduledStart = scheduledStart;}

    public Instant getStartedAt() { return startedAt; }
    public void setStartedAt(Instant startedAt) { this.startedAt = startedAt;}

    public Instant getEndedAt() { return endedAt; }
    public void setEndedAt(Instant endedAt) { this.endedAt = endedAt; }

    public String getCreatedBy() { return createdBy; }
    public void setCreatedBy(String createdBy) { this.createdBy = createdBy; }

    public Long getVersion() { return version; }
}
