package edu.escuelaing.campusseguro.events.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;

/**
 * Audit record that could not be delivered to MS08 yet (local outbox).
 * Business operations never fail because of auditing: the record stays here
 * and a process retries it until it is sent.
 */
@Entity
@Table(name = "pending_audit_records")
public class PendingAuditEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Audited action (e.g. EVENT_CREATED). */
    @Column(name = "action", nullable = false, length = 60)
    private String action;

    /** User or process that did the action. */
    @Column(name = "actor", nullable = false, length = 64)
    private String actor;

    /** Related event, if any. */
    @Column(name = "event_id")
    private UUID eventId;

    /** Action data in JSON. */
    @Column(name = "payload", columnDefinition = "text")
    private String payload;

    /** Time when the action happened. */
    @Column(name = "occurred_at", nullable = false)
    private Instant occurredAt;

    /** Number of send attempts. */
    @Column(name = "attempts", nullable = false)
    private int attempts;

    /** Reason of the last failure. */
    @Column(name = "last_error", length = 500)
    private String lastError;

    /** Delivery time to MS08; empty while pending. */
    @Column(name = "sent_at")
    private Instant sentAt;

    public UUID getId() {
    }

    public String getAction() { return action; }
    public void setAction(String action) { this.action = action; }

    public String getActor() { return actor; }
    public void setActor(String actor) { this.actor = actor; }

    public UUID getEventId() { return eventId; }
    public void setEventId(UUID eventId) { this.eventId = eventId; }

    public String getPayload() { return payload; }
    public void setPayload(String payload) { this.payload = payload; }

    public Instant getOccurredAt() { return occurredAt; }
    public void setOccurredAt(Instant occurredAt) { this.occurredAt = occurredAt; }

    public int getAttempts() { return attempts; }
    public void setAttempts(int attempts) { this.attempts = attempts; }

    public String getLastError() { return lastError; }
    public void setLastError(String lastError) { this.lastError = lastError; }

    public Instant getSentAt() { return sentAt; }
    public void setSentAt(Instant sentAt) { this.sentAt = sentAt; }
}
