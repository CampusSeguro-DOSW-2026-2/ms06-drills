package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.entity.enums.EventStatus;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;

/**
 * Immutable record of each event status change: who, when and why.
 */
@Entity
@Table(name = "event_state_history")
public class EventStateHistoryEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event that changed. */
    @Column(name = "event_id", nullable = false, updatable = false)
    private UUID eventId;

    /** Previous status; empty on creation. */
    @Enumerated(EnumType.STRING)
    @Column(name = "from_status", length = 20)
    private EventStatus fromStatus;

    /** New status. */
    @Enumerated(EnumType.STRING)
    @Column(name = "to_status", nullable = false, length = 20)
    private EventStatus toStatus;

    /** User or process ({@code system}) that made the change. */
    @Column(name = "changed_by", nullable = false, length = 64)
    private String changedBy;

    /** Optional reason or note. */
    @Column(name = "reason", length = 300)
    private String reason;

    /** Time of the change. */
    @Column(name = "changed_at", nullable = false)
    private Instant changedAt;

    public UUID getId() { return id; }

    public UUID getEventId() { return eventId; }
    public void setEventId(UUID eventId) { this.eventId = eventId; }

    public EventStatus getFromStatus() { return fromStatus; }
    public void setFromStatus(EventStatus fromStatus) { this.fromStatus = fromStatus; }

    public EventStatus getToStatus() { return toStatus; }
    public void setToStatus(EventStatus toStatus) { this.toStatus = toStatus; }

    public String getChangedBy() { return changedBy; }
    public void setChangedBy(String changedBy) { this.changedBy = changedBy; }

    public String getReason() { return reason; }
    public void setReason(String reason) { this.reason = reason; }

    public Instant getChangedAt() { return changedAt; }
    public void setChangedAt(Instant changedAt) { this.changedAt = changedAt; }
}
