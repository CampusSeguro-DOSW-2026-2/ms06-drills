package edu.escuelaing.campusseguro.events.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * Automatic evaluation of an event, created when it finishes. It keeps a snapshot
 * of the CHI and BEI metrics at that moment so they do not change later.
 * There is at most one per event.
 */
@Entity
@Table(name = "event_evaluations")
public class EventEvaluationEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Evaluated event. */
    @Column(name = "event_id", nullable = false, updatable = false, unique = true)
    private UUID eventId;

    /** Time when it was created. */
    @Column(name = "evaluated_at", nullable = false)
    private Instant evaluatedAt;

    /** Check-ins registered (CHI). */
    @Column(name = "total_checkins")
    private Integer totalCheckins;

    /** Check-in participation percentage. */
    @Column(name = "checkin_participation_pct", precision = 5, scale = 2)
    private BigDecimal checkinParticipationPct;

    /** Incidents reported (BEI). */
    @Column(name = "total_incidents")
    private Integer totalIncidents;

    /** Cases attended by brigadiers. */
    @Column(name = "cases_attended")
    private Integer casesAttended;

    /** Cases resolved by brigadiers. */
    @Column(name = "cases_resolved")
    private Integer casesResolved;

    /** Average attention time of an incident, in seconds. */
    @Column(name = "avg_attention_seconds")
    private Long avgAttentionSeconds;

    /** Full metrics detail in JSON (performance per brigadier, etc.). */
    @Column(name = "details", columnDefinition = "text")
    private String details;

    public UUID getId() { return id; }

    public UUID getEventId() { return eventId; }
    public void setEventId(UUID eventId) { this.eventId = eventId; }

    public Instant getEvaluatedAt() { return evaluatedAt; }
    public void setEvaluatedAt(Instant evaluatedAt) { this.evaluatedAt = evaluatedAt; }

    public Integer getTotalCheckins() { return totalCheckins; }
    public void setTotalCheckins(Integer totalCheckins) { this.totalCheckins = totalCheckins; }

    public BigDecimal getCheckinParticipationPct() { return checkinParticipationPct; }
    public void setCheckinParticipationPct(BigDecimal checkinParticipationPct) { this.checkinParticipationPct = checkinParticipationPct; }

    public Integer getTotalIncidents() { return totalIncidents; }
    public void setTotalIncidents(Integer totalIncidents) { this.totalIncidents = totalIncidents; }

    public Integer getCasesAttended() { return casesAttended; }
    public void setCasesAttended(Integer casesAttended) { this.casesAttended = casesAttended; }

    public Integer getCasesResolved() { return casesResolved; }
    public void setCasesResolved(Integer casesResolved) { this.casesResolved = casesResolved; }

    public Long getAvgAttentionSeconds() { return avgAttentionSeconds; }
    public void setAvgAttentionSeconds(Long avgAttentionSeconds) { this.avgAttentionSeconds = avgAttentionSeconds; }

    public String getDetails() { return details; }
    public void setDetails(String details) { this.details = details; }
}
