package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.entity.enums.EventAlertPurpose;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.util.UUID;

/**
 * Link between an event and an alert it created. An event
 * can have several alerts, each with a different purpose.
 */
@Entity
@Table(name = "event_alerts")
public class EventAlertEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event that owns the alert. */
    @Column(name = "event_id", nullable = false, updatable = false)
    private UUID eventId;

    /** Alert identifier in ALE. */
    @Column(name = "alert_id", nullable = false, length = 64)
    private String alertId;

    /** Why it was created. */
    @Enumerated(EnumType.STRING)
    @Column(name = "purpose", nullable = false, length = 20)
    private EventAlertPurpose purpose;

    public UUID getId() { return id; }

    public UUID getEventId() { return eventId; }
    public void setEventId(UUID eventId) { this.eventId = eventId; }
    
    public String getAlertId() { return alertId; }
    public void setAlertId(String alertId) { this.alertId = alertId; }

    public EventAlertPurpose getPurpose() { return purpose; }
    public void setPurpose(EventAlertPurpose purpose) { this.purpose = purpose; }
}
