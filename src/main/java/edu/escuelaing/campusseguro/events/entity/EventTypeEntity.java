package edu.escuelaing.campusseguro.events.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.util.UUID;

/**
 * Event type from the catalog (Drill, Earthquake, Fire, Riots, Flood, Chemical
 * Spill and Other, plus those added by a coordinator).
 *
 * <p>The code identifies the type in a stable way; the type with code
 * {@code SIMULACRO} is the one that makes an event a drill.
 */
@Entity
@Table(name = "event_types")
public class EventTypeEntity extends BaseEntity {

    /** Code of the type that makes an event a drill. */
    public static final String SIMULACRO_CODE = "SIMULACRO";

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Stable uppercase code, unique (e.g. SIMULACRO, SISMO). */
    @Column(name = "code", nullable = false, unique = true, length = 40)
    private String code;

    /** Display name, unique. */
    @Column(name = "name", nullable = false, unique = true, length = 80)
    private String name;

    /** If active, it can be assigned to new events. */
    @Column(name = "active", nullable = false)
    private boolean active;

    /** User who created the type ({@code system} for the predefined ones). */
    @Column(name = "created_by", nullable = false, length = 64)
    private String createdBy;

    public UUID getId() { return id; }

    public String getCode() { return code; }
    public void setCode(String code) { this.code = code; }

    public String getName() { return name; }

    public void setName(String name) { this.name = name; }

    public boolean isActive() { return active; }

    public void setActive(boolean active) { this.active = active; }

    public String getCreatedBy() { return createdBy; }

    public void setCreatedBy(String createdBy) { this.createdBy = createdBy; }
}
