package edu.escuelaing.campusseguro.events.entity;

import edu.escuelaing.campusseguro.events.entity.enums.ScopeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.util.UUID;

/**
 * Building or zone (from CAM) that is part of an event scope. An event has
 * many scope items and each item belongs to only one event.
 */
@Entity
@Table(name = "event_scope_items")
public class EventScopeItemEntity extends BaseEntity {

    /** Unique identifier (UUID generated by the system). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    /** Event it belongs to. */
    @Column(name = "event_id", nullable = false, updatable = false)
    private UUID eventId;

    /** Building or zone. */
    @Enumerated(EnumType.STRING)
    @Column(name = "scope_type", nullable = false, length = 20)
    private ScopeType scopeType;

    /** Building or zone identifier in CAM. */
    @Column(name = "scope_ref_id", nullable = false, length = 64)
    private String scopeRefId;

    public UUID getId() { return id; }

    public UUID getEventId() { return eventId; }
    public void setEventId(UUID eventId) { this.eventId = eventId; }

    public ScopeType getScopeType() { return scopeType; }
    public void setScopeType(ScopeType scopeType) { this.scopeType = scopeType; }

    public String getScopeRefId() { return scopeRefId; }
    public void setScopeRefId(String scopeRefId) { this.scopeRefId = scopeRefId; }
}
